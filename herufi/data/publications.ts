export type Publication = {
  /** Unique id. Blog posts can reference this via the `publication` frontmatter field. */
  id: string
  title: string
  category: string
  summary: string
  date: string
  format: string
  fileUrl: string
  tags: string[]
  /** Original author(s), for publications not authored by Herufi. */
  author?: string
  /** Originating institution, for curated third party research. */
  source?: string
  /** Extra credit context, e.g. noting a Herufi affiliation for one of the authors. */
  authorNote?: string
  /** Id of the series in `publicationSeries` below. Omitted for curated third party research. */
  series?: string
}

